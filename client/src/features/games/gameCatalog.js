export const GAME_THEME_BY_KEY = Object.fromEntries(
  GAME_LIBRARY.map((game) => [game.key, game])
);

export const GAME_OPTIONS = [
  { value: "any", label: "Any game" },
  ...GAME_LIBRARY.map((game) => ({ value: game.key, label: game.title })),
];

